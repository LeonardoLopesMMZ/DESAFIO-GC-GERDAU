CREATE TABLE IF NOT EXISTS base_original (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_servico     VARCHAR(40),
    codigo_fornecedor VARCHAR(12),
    codigo_servico    VARCHAR(10),
    descricao_item    VARCHAR(60),
    unidade_medida    VARCHAR(5)
);

CREATE TABLE IF NOT EXISTS codigo_servico (
    codigo           VARCHAR(10)  PRIMARY KEY,
    descricao        VARCHAR(60)  NOT NULL,
    descricao_limpa  VARCHAR(200),
    descricao_padrao VARCHAR(40),
    unidade          VARCHAR(5)   NOT NULL,
    grupo            VARCHAR(40)  NOT NULL,
    categoria        VARCHAR(40),
    status           VARCHAR(10)  NOT NULL DEFAULT 'ATIVO',
    codigo_canonico  VARCHAR(10)  REFERENCES codigo_servico (codigo),
    motivo           VARCHAR(80),
    criado_por       VARCHAR(60),
    criado_em        TIMESTAMP
);

CREATE SEQUENCE IF NOT EXISTS codigo_novo START WITH 9000001;

CREATE TABLE IF NOT EXISTS codigo_fornecedor (
    codigo     VARCHAR(10) NOT NULL REFERENCES codigo_servico (codigo),
    fornecedor VARCHAR(12) NOT NULL,
    PRIMARY KEY (codigo, fornecedor)
);

CREATE TABLE IF NOT EXISTS dicionario (
    termo  VARCHAR(30) PRIMARY KEY,
    padrao VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS solicitacao (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao_digitada VARCHAR(40)  NOT NULL,
    unidade            VARCHAR(5)   NOT NULL,
    grupo              VARCHAR(40),
    solicitante        VARCHAR(60)  NOT NULL,
    resultado          VARCHAR(10),
    codigo_sugerido    VARCHAR(10),
    codigo_escolhido   VARCHAR(10),
    candidatos         VARCHAR(200),
    justificativa      VARCHAR(200),
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    criada_em          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    metodo             VARCHAR(10),
    retrato_id         BIGINT,
    curador            VARCHAR(60),
    decidida_em        TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(60)   NOT NULL UNIQUE,
    credencial_id VARCHAR(400)  UNIQUE,
    chave_publica VARCHAR(1200),
    algoritmo     INT,
    contador      BIGINT        NOT NULL DEFAULT 0,
    rosto         VARCHAR(800),
    retrato_id    BIGINT,
    perfil        VARCHAR(10)   NOT NULL DEFAULT 'COMPRADOR',
    criado_em     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS retrato (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(60)  NOT NULL,
    tipo       VARCHAR(10)  NOT NULL,
    distancia  DOUBLE PRECISION,
    foto       BYTEA        NOT NULL,
    tirado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS aprendizado (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave      VARCHAR(220) NOT NULL,
    descricao  VARCHAR(60)  NOT NULL,
    unidade    VARCHAR(5)   NOT NULL,
    codigo     VARCHAR(10)  NOT NULL,
    tipo       VARCHAR(10)  NOT NULL,
    votos      INT          NOT NULL DEFAULT 0,
    ultimo_por VARCHAR(60),
    ultimo_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (chave, codigo, tipo)
);

CREATE TABLE IF NOT EXISTS palavra_aprendida (
    termo      VARCHAR(40)  PRIMARY KEY,
    correcao   VARCHAR(40)  NOT NULL,
    votos      INT          NOT NULL DEFAULT 0,
    status     VARCHAR(10)  NOT NULL DEFAULT 'SUGERIDA',
    ultimo_por VARCHAR(60),
    ultimo_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auditoria (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quando  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    quem    VARCHAR(60),
    acao    VARCHAR(40)  NOT NULL,
    alvo    VARCHAR(80),
    detalhe VARCHAR(300),
    ip      VARCHAR(45)
);
